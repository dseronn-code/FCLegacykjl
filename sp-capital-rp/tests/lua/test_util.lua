local U = SPC.Util

describe('Util.formatBRL', function()
    it('formata centavos', function()
        eq(U.formatBRL(0), 'R$ 0,00')
        eq(U.formatBRL(5), 'R$ 0,05')
        eq(U.formatBRL(123456), 'R$ 1.234,56')
        eq(U.formatBRL(500000), 'R$ 5.000,00')
        eq(U.formatBRL(100000000), 'R$ 1.000.000,00')
        eq(U.formatBRL(-99950), '-R$ 999,50')
    end)
end)

describe('Util.ulid', function()
    it('26 caracteres Crockford, ordenável por tempo', function()
        local a = U.ulid(1731240000000, math.random)
        local b = U.ulid(1731240000001, math.random)
        eq(#a, 26); truthy(U.isUlid(a)); truthy(a:sub(1, 10) < b:sub(1, 10))
    end)
    it('isUlid recusa inválidos', function()
        truthy(not U.isUlid('abc')); truthy(not U.isUlid(('I'):rep(26))); truthy(not U.isUlid(nil))
    end)
end)

describe('RateLimit', function()
    it('bloqueia dentro do intervalo e libera depois', function()
        local rl = SPC.RateLimit.new()
        truthy(rl:allow('1:x', 1000, 0))
        truthy(not rl:allow('1:x', 1000, 999))
        truthy(rl:allow('1:x', 1000, 1000))
        truthy(rl:allow('2:x', 1000, 1000))
    end)
    it('clear remove por prefixo', function()
        local rl = SPC.RateLimit.new()
        rl:allow('1:a', 1000, 0); rl:allow('12:a', 1000, 0)
        rl:clear('1:')
        truthy(rl:allow('1:a', 1000, 1)); truthy(not rl:allow('12:a', 1000, 1))
    end)
end)

describe('Util.bindNulls', function()
    it('nil vira NULL sem deslocar os parâmetros seguintes', function()
        local sql, p = U.bindNulls('INSERT INTO t (a, b, c, d) VALUES (?, ?, ?, ?)', { 1, nil, 'x', nil })
        eq(sql, 'INSERT INTO t (a, b, c, d) VALUES (?, NULL, ?, NULL)'); eq(#p, 2); eq(p[1], 1); eq(p[2], 'x')
    end)
    it('sem nil mantém tudo', function()
        local sql, p = U.bindNulls('a = ? AND b = ?', { 1, 2 }); eq(sql, 'a = ? AND b = ?'); eq(#p, 2)
    end)
    it('sem parâmetros', function() local sql, p = U.bindNulls('SELECT 1'); eq(sql, 'SELECT 1'); eq(p, nil) end)
    it('false é valor, não NULL', function()
        local sql, p = U.bindNulls('?', { false }); eq(sql, '?'); eq(p[1], false)
    end)
end)
