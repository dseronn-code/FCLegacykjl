local N = dofile('game/resources/[spc-core]/spc_needs/shared/needs_core.lua')

describe('Needs', function()
    it('normaliza status vazio/inválido para o padrão', function()
        local s = N.normalize({ hunger = 'x', thirst = 150 })
        eq(s.hunger, 100); eq(s.thirst, 100); eq(s.stress, 0)
        eq(N.normalize(nil).hunger, 100)
    end)
    it('decai no ritmo da spec (fome ~3h, sede ~2h)', function()
        local s = N.decay({ hunger = 100, thirst = 100, stress = 10 }, 60)
        eq(s.hunger, 67); eq(s.thirst, 50.2); eq(s.stress, 0)
        eq(N.decay({ hunger = 1, thirst = 1 }, 10).hunger, 0)
    end)
    it('pausado não decai fome/sede; preso decai pela metade', function()
        eq(N.decay({ hunger = 50, thirst = 50 }, 10, 0).hunger, 50)
        eq(N.decay({ hunger = 50, thirst = 50 }, 10, 0.5).hunger, 47.25)
    end)
    it('itens aplicam a tabela e respeitam 0–100', function()
        local s = N.applyItem({ hunger = 90, thirst = 10, stress = 1 }, 'pastel')
        eq(s.hunger, 100); eq(s.thirst, 5); eq(s.stress, 0)
        eq(N.applyItem({}, 'lockpick'), nil)
    end)
    it('dano só com fome ou sede zerada', function()
        eq(N.starveDamage({ hunger = 0, thirst = 50 }), 5); eq(N.starveDamage({ hunger = 1, thirst = 1 }), 0)
        truthy(N.isLow({ hunger = 14, thirst = 90 })); truthy(not N.isLow({ hunger = 15, thirst = 15 }))
    end)
end)
