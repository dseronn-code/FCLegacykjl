dofile('game/resources/[spc-core]/spc_bank/shared/config.lua')
local B = dofile('game/resources/[spc-core]/spc_bank/shared/bank_core.lua')
local L = SPCBank.Config.Limits

describe('Bank', function()
    it('valor inteiro positivo dentro do limite', function()
        eq(B.parseAmount(500, 2000), 500); eq(B.parseAmount('20', 2000), 20)
        local v, e = B.parseAmount(2001, 2000); eq(v, nil); eq(e, 'over_limit')
        for _, x in ipairs({ 0, -5, 1.5, 'abc' }) do local _, err = B.parseAmount(x, 10); eq(err, 'invalid_amount', tostring(x)) end
    end)
    it('agência mais próxima dentro de 3 m', function()
        local br = SPCBank.Config.Branches
        truthy(B.nearBranch({ x = 150.5, y = -1041, z = 29.37 }, br, 3.0))
        eq(B.nearBranch({ x = 0, y = 0, z = 0 }, br, 3.0), nil)
    end)
    it('imposto do PIX: 1% só acima de R$ 50.000', function()
        eq(B.pixTax(50000, L.PixTaxThreshold, L.PixTaxPercent), 0)
        eq(B.pixTax(50001, L.PixTaxThreshold, L.PixTaxPercent), 500)
        eq(B.pixTax(80000, L.PixTaxThreshold, L.PixTaxPercent), 800)
    end)
    it('movimentos do PIX em centavos com imposto na mesma transação', function()
        local legs, tax = B.pixLegs(1, 2, 60000, L)
        eq(#legs, 2); eq(legs[1].amount, 6000000); eq(legs[2].amount, 60000); eq(legs[2].to.system, 'SINK_TAX'); eq(tax, 600)
        eq(#B.pixLegs(1, 2, 100, L), 1)
    end)
    it('normaliza telefone como chave PIX', function()
        eq(B.normalizePhone('11912345678'), '(11) 91234-5678')
        eq(B.normalizePhone('(11) 91234-5678'), '(11) 91234-5678')
        eq(B.normalizePhone('2191234567'), nil); eq(B.normalizePhone(nil), nil)
    end)
end)
