local I = SPC.Identity
math.randomseed(42)
local rand = math.random

describe('Identity.citizenId', function()
    it('tem 8 caracteres e prefixo SPC', function()
        for _ = 1, 200 do
            local id = I.citizenId(rand)
            eq(#id, 8); truthy(id:match('^SPC[0-9A-Z]+$'), id)
        end
    end)
end)

describe('Identity.cpf', function()
    it('gera formato válido, aceito pela regra do jogo e NUNCA válido pela regra real', function()
        for _ = 1, 5000 do
            local cpf = I.cpf(rand)
            truthy(cpf:match('^%d%d%d%.%d%d%d%.%d%d%d%-%d%d$'), cpf)
            truthy(I.isGameCpf(cpf), 'regra do jogo: ' .. cpf)
            truthy(not I.isRealCpf(cpf), 'coincide com CPF real: ' .. cpf)
        end
    end)
    it('reconhece CPF real conhecido de exemplo (111.444.777-35)', function()
        truthy(I.isRealCpf('111.444.777-35'))
        truthy(not I.isGameCpf('111.444.777-35'))
    end)
    it('recusa formato inválido', function()
        truthy(not I.isGameCpf('11144477735')); truthy(not I.isGameCpf(nil))
    end)
end)

describe('Identity.rg / phone', function()
    it('formatos', function()
        truthy(I.rg(rand):match('^%d%d%.%d%d%d%.%d%d%d%-%d$'))
        truthy(I.phone(rand):match('^%(11%) 9%d%d%d%d%-%d%d%d%d$'))
    end)
end)

describe('Identity.normalizeName', function()
    local blocked = SPC.Config.BlockedNameWords
    it('normaliza capitalização com acentos', function()
        eq(I.normalizeName('  joão   da SILVA ', blocked), 'João Da Silva')
        eq(I.normalizeName('ÁLVARO', blocked), 'Álvaro')
        eq(I.normalizeName("d'ávila-souza", blocked), "D'Ávila-Souza")
    end)
    it('recusa tamanho fora de 2–20', function()
        local _, e = I.normalizeName('A', blocked); eq(e, 'invalid_name_length')
        _, e = I.normalizeName(('a'):rep(21), blocked); eq(e, 'invalid_name_length')
    end)
    it('recusa números, símbolos e emoji', function()
        local _, e = I.normalizeName('Jo4o', blocked); eq(e, 'invalid_name_chars')
        _, e = I.normalizeName('João 😀', blocked); eq(e, 'invalid_name_chars')
        _, e = I.normalizeName('--', blocked); eq(e, 'invalid_name_chars')
    end)
    it('recusa palavras bloqueadas mesmo com acento', function()
        local _, e = I.normalizeName('Políciaman', blocked); eq(e, 'blocked_name')
    end)
    it('recusa UTF-8 inválido e não-string', function()
        local _, e = I.normalizeName('\xff\xfe', blocked); eq(e, 'invalid_name')
        _, e = I.normalizeName(123, blocked); eq(e, 'invalid_name')
    end)
end)

describe('Identity.validateBirthdate', function()
    local today = { year = 2026, month = 11, day = 10 }
    it('aceita adulto', function() truthy(I.validateBirthdate('2000-02-29', today, 18, 90)) end)
    it('recusa 29/02 em ano não bissexto', function()
        local ok, e = I.validateBirthdate('2001-02-29', today, 18, 90); truthy(not ok); eq(e, 'invalid_birthdate')
    end)
    it('limite de 18 anos é exato no dia', function()
        truthy(I.validateBirthdate('2008-11-10', today, 18, 90))
        local ok, e = I.validateBirthdate('2008-11-11', today, 18, 90); truthy(not ok); eq(e, 'invalid_age')
    end)
    it('recusa formato errado', function()
        truthy(not I.validateBirthdate('10/11/2000', today, 18, 90))
        truthy(not I.validateBirthdate('2000-13-01', today, 18, 90))
    end)
end)
